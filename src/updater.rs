struct UpdateRuntime {
    updates: Arc<UpdateController>,
    before_exit: Arc<dyn Fn() + Send + Sync>,
}

static RUNTIME: OnceLock<UpdateRuntime> = OnceLock::new();

/// Registers the single process-wide hook used by [`apply_pending_update`].
pub fn install_runtime(
    updates: Arc<UpdateController>,
    before_exit: impl Fn() + Send + Sync + 'static,
) {
    let _ = RUNTIME.set(UpdateRuntime {
        updates,
        before_exit: Arc::new(before_exit),
    });
}

/// Single entry point for installing a discovered update. All UI surfaces must
/// call this and only this when the user chooses to update now.
/// Progress and failures are shown on the update card.
pub fn apply_pending_update() -> Result<()> {
    let runtime = match RUNTIME.get().context("update runtime is not installed") {
        Ok(runtime) => runtime,
        Err(error) => return Err(report_update_failure(error)),
    };
    // A second click while the first one is still downloading.
    if runtime.updates.snapshot() == UpdatePhase::Applying {
        return Ok(());
    }
    if let Err(error) = runtime.updates.apply() {
        return Err(report_update_failure(error));
    }
    // Let the card show its last step before the process goes away; the
    // helper waits for this process to exit anyway.
    thread::sleep(RESTART_NOTICE);
    (runtime.before_exit)();
    release_for_update();
    std::process::exit(0);
}

fn report_update_failure(error: anyhow::Error) -> anyhow::Error {
    crate::logger::info(format!("failed to apply update: {error:#}"));
    notifications::show_update_failed(&error);
    error
}

/// How long the "Restarting" step stays up before the process exits.
const RESTART_NOTICE: Duration = Duration::from_millis(600);
/// Minimum spacing of progress updates sent to the update card.
const PROGRESS_INTERVAL: Duration = Duration::from_millis(80);

/// Rate-limits progress updates; the final one always goes through.
struct ProgressThrottle(Option<Instant>);

impl ProgressThrottle {
    fn new() -> Self {
        Self(None)
    }

    fn ready(&mut self, done: bool) -> bool {
        let now = Instant::now();
        if done
            || self
                .0
                .is_none_or(|last| now.duration_since(last) >= PROGRESS_INTERVAL)
        {
            self.0 = Some(now);
            return true;
        }
        false
    }
}

fn megabytes(bytes: u64) -> String {
    format!("{:.1} MB", bytes as f64 / (1024.0 * 1024.0))
}

/// Before the first byte arrives the bar sweeps under the version.
fn report_download_started(version: &str) {
    notifications::show_update_progress(
        crate::i18n::tr("update-downloading"),
        &format!("Codex Minibar {version}"),
        notifications::Progress::Indeterminate,
    );
}

fn report_download(downloaded: u64, total: Option<u64>) {
    let (body, progress) = match total.filter(|total| *total > 0) {
        Some(total) => (
            crate::i18n::format(
                "update-download-progress",
                &[
                    ("downloaded", megabytes(downloaded.min(total))),
                    ("total", megabytes(total)),
                ],
            ),
            notifications::Progress::Fraction(downloaded as f32 / total as f32),
        ),
        None => (
            crate::i18n::format(
                "update-downloaded",
                &[("downloaded", megabytes(downloaded))],
            ),
            notifications::Progress::Indeterminate,
        ),
    };
    notifications::show_update_progress(crate::i18n::tr("update-downloading"), &body, progress);
}

fn report_unpack(done: usize, total: usize) {
    notifications::show_update_progress(
        crate::i18n::tr("update-installing"),
        crate::i18n::tr("update-unpacking"),
        notifications::Progress::Fraction(if total == 0 {
            1.0
        } else {
            done as f32 / total as f32
        }),
    );
}

fn report_restart() {
    notifications::show_update_progress(
        crate::i18n::tr("update-restarting"),
        crate::i18n::tr("update-restarting-body"),
        notifications::Progress::Fraction(1.0),
    );
}

/// Opens the GitHub release page for the pending update, or the releases index.
pub fn open_release_notes() -> Result<()> {
    let url = RUNTIME
        .get()
        .and_then(|runtime| runtime.updates.available_update())
        .map(|update| update.html_url)
        .unwrap_or_else(|| RELEASES_URL.to_string());
    crate::shell::open_url(&url)
}

/// Announces a finished in-place update, then sweeps the install directory
/// in the background.
pub fn finish_startup() {
    let updated = match take_post_update_success_marker() {
        Ok(version) => version,
        Err(error) => {
            crate::logger::info(format!("failed to read post-update marker: {error:#}"));
            None
        }
    };
    if let Some(version) = &updated {
        notifications::notify(update_complete_notification(version));
    }
    // The helper that relaunched us is still running and removes its own
    // staging (`finally` in apply-update.ps1); leave it to the helper then.
    let sweep_staging = updated.is_none();
    thread::spawn(move || cleanup_install_dir(sweep_staging));
}

/// The finished-update card; [`crate::whats_new`] fills in the summary.
fn update_complete_notification(version: &str) -> notifications::Notification {
    notifications::Notification::new(
        notifications::NotificationKind::Success,
        crate::i18n::tr("update-complete"),
        &crate::i18n::format("now-running-version", &[("version", version.to_string())]),
    )
    .keyed(notifications::UPDATE_COMPLETE_KEY)
}

/// Keeps Windows "Installed apps" DisplayVersion in sync with this binary.
/// Zip updates replace files but do not rewrite the NSIS uninstall registry.
pub fn sync_installed_display_version() {
    #[cfg(windows)]
    if let Err(error) = sync_uninstall_display_version(env!("CARGO_PKG_VERSION")) {
        eprintln!("failed to sync installed display version: {error:#}");
    }
}

#[cfg(windows)]
fn sync_uninstall_display_version(version: &str) -> Result<()> {
    use windows_sys::Win32::System::Registry::HKEY_CURRENT_USER;
    // Installer writes HKCU (RequestExecutionLevel user) for each arch package.
    for arch in ["x86", "x64", "arm64"] {
        let subkey =
            format!(r"Software\Microsoft\Windows\CurrentVersion\Uninstall\Codex Minibar {arch}");
        let Some(key) = crate::win32::RegKey::open_for_write(HKEY_CURRENT_USER, subkey) else {
            continue;
        };
        if let Err(status) = key.set_string("DisplayVersion", version) {
            bail!("RegSetValueExW(DisplayVersion) for {arch}: {status}");
        }
    }
    Ok(())
}

/// Removes files that earlier releases installed and this one no longer
/// ships: the WinUI runtime, assets dropped since, and leftover update
/// staging. Zip updates only copy the new package over the install.
fn cleanup_install_dir(sweep_staging: bool) {
    let dir = match install_dir() {
        Ok(dir) => dir,
        Err(error) => {
            eprintln!("install cleanup skipped: {error:#}");
            return;
        }
    };
    let mut removed = 0;
    removed += remove_legacy_winui(&dir);
    removed += prune_stale_assets(&dir.join("assets"));
    if sweep_staging {
        removed += remove_update_staging(&dir.join(UPDATE_STAGING_DIR));
    }
    if removed > 0 {
        crate::logger::info(format!(
            "Removed {removed} stale item(s) from {}",
            dir.display()
        ));
    }
}

fn remove_legacy_winui(dir: &Path) -> usize {
    let mut removed = 0;
    for name in LEGACY_WINUI_FILES {
        removed += usize::from(fs::remove_file(dir.join(name)).is_ok());
    }
    removed += usize::from(fs::remove_dir_all(dir.join(LEGACY_WINUI_DIR)).is_ok());

    let Ok(entries) = fs::read_dir(dir) else {
        return removed;
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        if path.is_dir() && is_legacy_locale_dir(&path) {
            for name in LEGACY_WINUI_LOCALE_FILES {
                let _ = fs::remove_file(path.join(name));
            }
            removed += usize::from(fs::remove_dir(&path).is_ok());
        }
    }
    removed
}

/// True when the folder holds nothing but WinUI locale resources, so folders
/// with anything else in them are never touched.
fn is_legacy_locale_dir(path: &Path) -> bool {
    let Ok(entries) = fs::read_dir(path) else {
        return false;
    };
    let mut any = false;
    for entry in entries {
        let Ok(entry) = entry else {
            return false;
        };
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let known = LEGACY_WINUI_LOCALE_FILES
            .iter()
            .any(|legacy| legacy.eq_ignore_ascii_case(&name));
        if !known || !entry.file_type().is_ok_and(|kind| kind.is_file()) {
            return false;
        }
        any = true;
    }
    any
}

fn prune_stale_assets(assets: &Path) -> usize {
    if PACKAGED_ASSETS.is_empty() || !assets.is_dir() {
        return 0;
    }
    prune_stale_assets_in(assets, assets)
}

fn prune_stale_assets_in(root: &Path, dir: &Path) -> usize {
    let Ok(entries) = fs::read_dir(dir) else {
        return 0;
    };
    let mut removed = 0;
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() {
            removed += prune_stale_assets_in(root, &path);
            // Only succeeds once the folder is empty.
            removed += usize::from(fs::remove_dir(&path).is_ok());
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let relative = relative.to_string_lossy().replace('\\', "/");
        let packaged = PACKAGED_ASSETS
            .iter()
            .any(|asset| asset.eq_ignore_ascii_case(&relative));
        if !packaged {
            removed += usize::from(fs::remove_file(&path).is_ok());
        }
    }
    removed
}

/// Drops staging left by finished or failed updates, keeping this process's
/// own run directory in case an update is being applied right now.
fn remove_update_staging(staging: &Path) -> usize {
    let Ok(entries) = fs::read_dir(staging) else {
        return 0;
    };
    let own = format!("run-{}", std::process::id());
    let mut removed = 0;
    for entry in entries.filter_map(Result::ok) {
        if entry.file_name() != own.as_str() {
            removed += usize::from(fs::remove_dir_all(entry.path()).is_ok());
        }
    }
    removed + usize::from(fs::remove_dir(staging).is_ok())
}

fn take_post_update_success_marker() -> Result<Option<String>> {
    let path = install_dir()?.join(UPDATE_SUCCESS_MARKER);
    if !path.exists() {
        return Ok(None);
    }
    let version = fs::read_to_string(&path)
        .with_context(|| format!("read {}", path.display()))?
        .trim()
        .to_string();
    let _ = fs::remove_file(&path);
    if version.is_empty() {
        return Ok(None);
    }
    Ok(Some(version))
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AvailableUpdate {
    pub version: String,
    pub asset_url: String,
    pub html_url: String,
    /// Asset size reported by the GitHub API, if any.
    pub size: Option<u64>,
    /// Expected lowercase hex SHA-256 reported by the GitHub API, if any.
    pub sha256: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum UpdatePhase {
    Idle,
    Checking,
    UpToDate,
    Available(AvailableUpdate),
    Applying,
    Failed(String),
}

struct InnerState {
    phase: UpdatePhase,
    notified_version: Option<String>,
}

pub struct UpdateController {
    inner: Mutex<InnerState>,
}

impl UpdateController {
    pub fn new() -> Arc<Self> {
        Arc::new(Self {
            inner: Mutex::new(InnerState {
                phase: UpdatePhase::Idle,
                notified_version: None,
            }),
        })
    }

    pub fn snapshot(&self) -> UpdatePhase {
        self.inner
            .lock()
            .expect("update controller lock")
            .phase
            .clone()
    }

    pub fn available_update(&self) -> Option<AvailableUpdate> {
        match self.snapshot() {
            UpdatePhase::Available(update) => Some(update),
            _ => None,
        }
    }

    fn set_phase(&self, phase: UpdatePhase) {
        self.inner.lock().expect("update controller lock").phase = phase;
    }

    /// Checks for an update in the background; `notify` announces a newly
    /// found version on a card.
    pub fn check_async(self: &Arc<Self>, notify: bool) {
        let controller = Arc::clone(self);
        thread::spawn(move || {
            if let Err(error) = controller.check_once(notify) {
                eprintln!("update check failed: {error:#}");
                controller.set_phase(UpdatePhase::Failed(error.to_string()));
            }
        });
    }

    fn check_once(&self, notify: bool) -> Result<()> {
        self.set_phase(UpdatePhase::Checking);
        match check_for_update()? {
            Some(update) => {
                let should_notify = notify
                    && self
                        .inner
                        .lock()
                        .expect("update controller lock")
                        .notified_version
                        .as_deref()
                        != Some(update.version.as_str());
                if should_notify {
                    notifications::show_update_available(&update.version, &update.html_url);
                    self.inner
                        .lock()
                        .expect("update controller lock")
                        .notified_version = Some(update.version.clone());
                }
                self.set_phase(UpdatePhase::Available(update));
            }
            None => self.set_phase(UpdatePhase::UpToDate),
        }
        Ok(())
    }

    pub fn apply(&self) -> Result<()> {
        let update = self.available_update().context("no update is available")?;
        self.set_phase(UpdatePhase::Applying);
        let result = apply_update(&update);
        if result.is_err() {
            // Restore the previous phase so the update stays retryable and the
            // About page's check button is not blocked.
            self.set_phase(UpdatePhase::Available(update));
        }
        result
    }
}

#[derive(Debug, Deserialize)]
struct GhRelease {
    tag_name: String,
    html_url: String,
    assets: Vec<GhAsset>,
}

#[derive(Debug, Deserialize)]
struct GhAsset {
    name: String,
    browser_download_url: String,
    #[serde(default)]
    size: Option<u64>,
    #[serde(default)]
    digest: Option<String>,
}

/// Hard upper bound for a downloaded release package.
const MAX_UPDATE_DOWNLOAD_BYTES: u64 = 200 * 1024 * 1024;

/// Extracts the lowercase hex SHA-256 from a GitHub `digest` field.
fn parse_sha256_digest(digest: &str) -> Option<String> {
    let hex = digest.trim().strip_prefix("sha256:")?;
    (hex.len() == 64 && hex.bytes().all(|b| b.is_ascii_hexdigit()))
        .then(|| hex.to_ascii_lowercase())
}

pub fn current_version() -> Version {
    Version::parse(env!("CARGO_PKG_VERSION")).unwrap_or_else(|_| Version::new(0, 0, 0))
}

pub fn host_arch() -> &'static str {
    #[cfg(all(target_arch = "x86_64", target_pointer_width = "64"))]
    {
        "x64"
    }
    #[cfg(all(target_arch = "x86", target_pointer_width = "32"))]
    {
        return "x86";
    }
    #[cfg(target_arch = "aarch64")]
    {
        return "arm64";
    }
    #[cfg(not(any(
        all(target_arch = "x86_64", target_pointer_width = "64"),
        all(target_arch = "x86", target_pointer_width = "32"),
        target_arch = "aarch64"
    )))]
    {
        "x64"
    }
}

fn check_for_update() -> Result<Option<AvailableUpdate>> {
    let release: GhRelease = github_get(LATEST_RELEASE_API)?;
    let remote = parse_release_version(&release.tag_name)?;
    let current = current_version();
    if remote <= current {
        return Ok(None);
    }

    let arch = host_arch();
    let expected_suffix = format!("-{arch}-portable.zip");
    let asset = release
        .assets
        .iter()
        .find(|asset| asset.name.ends_with(&expected_suffix))
        .with_context(|| {
            format!(
                "release {} has no portable zip asset for {arch} (*{expected_suffix})",
                release.tag_name
            )
        })?;

    Ok(Some(AvailableUpdate {
        version: remote.to_string(),
        asset_url: asset.browser_download_url.clone(),
        html_url: release.html_url,
        size: asset.size,
        sha256: asset.digest.as_deref().and_then(parse_sha256_digest),
    }))
}

fn parse_release_version(tag: &str) -> Result<Version> {
    let trimmed = tag.trim();
    // Accept "v1.2.3", "V1.2.3", "v.1.2.3", "V.1.2.3", and bare "1.2.3".
    let without_prefix = trimmed
        .strip_prefix("v.")
        .or_else(|| trimmed.strip_prefix("V."))
        .or_else(|| trimmed.strip_prefix('v'))
        .or_else(|| trimmed.strip_prefix('V'))
        .unwrap_or(trimmed)
        .trim_start_matches('.');
    Version::parse(without_prefix).with_context(|| format!("parse release tag {tag:?}"))
}

fn github_get(url: &str) -> Result<GhRelease> {
    let response = crate::net::shared_agent()
        .get(url)
        .set("Accept", "application/vnd.github+json")
        .call()
        .with_context(|| format!("GET {url}"))?;
    let status = response.status();
    let body = response
        .into_string()
        .with_context(|| format!("read GitHub response body ({status})"))?;
    if status / 100 != 2 {
        bail!("GitHub API returned {status}: {body}");
    }
    serde_json::from_str(&body).context("parse GitHub release JSON")
}

fn install_dir() -> Result<PathBuf> {
    std::env::current_exe()
        .context("resolve current executable")
        .and_then(|path| {
            path.parent()
                .map(Path::to_path_buf)
                .context("executable has no parent directory")
        })
}

fn install_dir_writable(dir: &Path) -> bool {
    let probe = dir.join(".codex-minibar-update-write-test");
    match fs::write(&probe, b"") {
        Ok(()) => {
            let _ = fs::remove_file(&probe);
            true
        }
        Err(_) => false,
    }
}

fn apply_update(update: &AvailableUpdate) -> Result<()> {
    report_download_started(&update.version);
    let install_dir = install_dir()?;
    if !install_dir_writable(&install_dir) {
        crate::shell::open_url(&update.html_url)?;
        bail!(
            "cannot update in place because {} is not writable; opened the release page in your browser",
            install_dir.display()
        );
    }

    let staging_root = install_dir.join(".update-staging");
    let run_dir = staging_root.join(format!("run-{}", std::process::id()));
    if run_dir.exists() {
        fs::remove_dir_all(&run_dir)
            .with_context(|| format!("clear previous update staging at {}", run_dir.display()))?;
    }
    fs::create_dir_all(&run_dir)
        .with_context(|| format!("create update staging at {}", run_dir.display()))?;

    let zip_path = run_dir.join("package.zip");
    let limit = update.size.map_or(MAX_UPDATE_DOWNLOAD_BYTES, |size| {
        size.min(MAX_UPDATE_DOWNLOAD_BYTES)
    });
    let mut throttle = ProgressThrottle::new();
    let digest = crate::net::download_limited(
        &update.asset_url,
        &zip_path,
        limit,
        &mut |downloaded, length| {
            let total = update.size.or(length);
            if throttle.ready(total == Some(downloaded)) {
                report_download(downloaded, total);
            }
        },
    )?;
    if let Some(expected) = &update.sha256
        && !digest.eq_ignore_ascii_case(expected)
    {
        let _ = fs::remove_file(&zip_path);
        bail!("update package checksum mismatch (expected {expected}, got {digest})");
    }
    let extracted = run_dir.join("extracted");
    fs::create_dir_all(&extracted).context("create extraction directory")?;
    let mut throttle = ProgressThrottle::new();
    let payload_root = extract_portable_zip(&zip_path, &extracted, &mut |done, total| {
        if throttle.ready(done == total) {
            report_unpack(done, total);
        }
    })?;

    let pid = std::process::id();
    let script_path = run_dir.join("apply-update.ps1");
    let script = format!(
        r#"$ErrorActionPreference = 'Stop'
$pidToWait = {pid}
$install = '{install}'
$source = '{source}'
$staging = '{staging}'
$exe = Join-Path $install '{APP_EXE}'

while (Get-Process -Id $pidToWait -ErrorAction SilentlyContinue) {{
    Start-Sleep -Milliseconds 250
}}

try {{
    Get-ChildItem -LiteralPath $source -Force | ForEach-Object {{
        Copy-Item -LiteralPath $_.FullName -Destination $install -Recurse -Force
    }}
    Set-Content -LiteralPath (Join-Path $install '{marker}') -Value '{version}' -Encoding utf8 -NoNewline
    foreach ($arch in @('x86', 'x64', 'arm64')) {{
        $key = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\Codex Minibar $arch"
        if (Test-Path -LiteralPath $key) {{
            Set-ItemProperty -LiteralPath $key -Name DisplayVersion -Value '{version}'
        }}
    }}
    Start-Process -FilePath $exe -WorkingDirectory $install
}} finally {{
    Start-Sleep -Seconds 2
    if (Test-Path -LiteralPath $staging) {{
        Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue
    }}
}}
"#,
        install = escape_ps_single_quoted(&install_dir),
        source = escape_ps_single_quoted(&payload_root),
        staging = escape_ps_single_quoted(&run_dir),
        marker = UPDATE_SUCCESS_MARKER,
        version = escape_ps_single_quoted_str(&update.version),
    );
    fs::write(&script_path, script).context("write update helper script")?;
    spawn_hidden_helper(&script_path).context("spawn update helper")?;
    report_restart();

    Ok(())
}

#[cfg(windows)]
fn spawn_hidden_helper(script_path: &Path) -> Result<()> {
    use std::os::windows::process::CommandExt;

    const CREATE_NO_WINDOW: u32 = 0x0800_0000;

    Command::new("powershell")
        .args([
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-WindowStyle",
            "Hidden",
            "-File",
        ])
        .arg(script_path)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .creation_flags(CREATE_NO_WINDOW)
        .spawn()
        .map(|_| ())
        .context("spawn hidden PowerShell update helper")
}

#[cfg(not(windows))]
fn spawn_hidden_helper(_script_path: &Path) -> Result<()> {
    bail!("in-place updates are only supported on Windows")
}

fn escape_ps_single_quoted(value: &Path) -> String {
    value.display().to_string().replace('\'', "''")
}

fn escape_ps_single_quoted_str(value: &str) -> String {
    value.replace('\'', "''")
}

/// Reports `(entries done, entries)` as it goes.
fn extract_portable_zip(
    archive_path: &Path,
    destination: &Path,
    on_progress: &mut dyn FnMut(usize, usize),
) -> Result<PathBuf> {
    let file =
        fs::File::open(archive_path).with_context(|| format!("open {}", archive_path.display()))?;
    let mut archive = ZipArchive::new(file).context("open update zip archive")?;
    let entries = archive.len();
    on_progress(0, entries);
    for index in 0..entries {
        on_progress(index, entries);
        let mut entry = archive.by_index(index).context("read zip entry")?;
        let Some(relative) = entry.enclosed_name() else {
            continue;
        };
        let target = destination.join(relative);
        if entry.is_dir() {
            fs::create_dir_all(&target).with_context(|| format!("create {}", target.display()))?;
            continue;
        }
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent).with_context(|| format!("create {}", parent.display()))?;
        }
        let mut output =
            fs::File::create(&target).with_context(|| format!("create {}", target.display()))?;
        copy(&mut entry, &mut output).with_context(|| format!("extract {}", target.display()))?;
    }
    on_progress(entries, entries);

    payload_root_from_extracted(destination)
}

fn payload_root_from_extracted(destination: &Path) -> Result<PathBuf> {
    let mut entries = fs::read_dir(destination)
        .with_context(|| format!("read {}", destination.display()))?
        .filter_map(Result::ok)
        .collect::<Vec<_>>();
    if entries.len() == 1 {
        let only = entries.remove(0);
        let file_type = only.file_type().context("inspect extracted entry")?;
        if file_type.is_dir() {
            return Ok(only.path());
        }
    }
    Ok(destination.to_path_buf())
}

